//4.logical operators:-these operators are used to combine two or more conditions return either true or false.it can be classified 3 types. they are
//1.logical AND(&&):-it returns true only if both conditions are true
let a=15;
let b=10;
console.log(a>b && b<a)
//logical NOT(||):-it returns true if atleast one conditions is true
let c=20;
let d=15;
console.log(c>d || d>c)
//logical OR(!):-reverse the result
let e=5;
let f=8;
console.log(!(e<f))






//2.comparison operators:-it is used to compare the two values and return either true or false.they are classified 6 types.they are,
//>,<,>=,<=,==,===
//example code:-
 let c=5;
 let d=10;
console.log(c>d)
console.log(c<d)
console.log(c>=d)
console.log(c<=d)
//==:-means return true when both values are equal
let e=10;
let f=10;
console.log(e==f)
//===:-means return true when both values are equal and datatypes are also equal
let g=10;
let h=10;
console.log(g===h)

//3.Assignment operators:-it is used to assign values to the variables
